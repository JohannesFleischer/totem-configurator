#!/usr/bin/env python3
"""Generate web/keycodes-data.ts from Vial GUI's keycode tables.

Reads vial-gui's keycodes.py / keycodes_v6.py with the `ast` module only (no code
from vial-gui is executed). Usage:
    python3 -I tools/gen_keycodes.py <vial-gui>/src/main/python/keycodes > web/keycodes-data.ts
"""
import ast
import json
import sys
from pathlib import Path

src_dir = Path(sys.argv[1])
kc_tree = ast.parse((src_dir / "keycodes.py").read_text())
v6_tree = ast.parse((src_dir / "keycodes_v6.py").read_text())

# --- v6 numbering: the literal dict assigned to `kc` inside class keycodes_v6
v6 = None
for node in ast.walk(v6_tree):
    if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "kc" for t in node.targets):
        v6 = ast.literal_eval(node.value)
assert v6, "v6 table not found"

# --- category lists: NAME = [ K("qmk_id", "label", "tooltip", masked=..., alias=[...], ...), ... ]
def parse_k(call):
    args = [ast.literal_eval(a) for a in call.args]
    kw = {k.arg: ast.literal_eval(k.value) for k in call.keywords}
    qmk_id = args[0]
    label = args[1]
    tooltip = args[2] if len(args) > 2 else kw.get("tooltip")
    return {
        "id": qmk_id,
        "label": label,
        "tooltip": tooltip,
        "alias": kw.get("alias", []),
        "masked": bool(kw.get("masked", False)),
        "feature": kw.get("requires_feature"),
        "printable": kw.get("printable"),
    }

lists = {}
for node in kc_tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        name = node.targets[0].id
        if name.startswith("KEYCODES_") and isinstance(node.value, ast.List):
            items = []
            for el in node.value.elts:
                if isinstance(el, ast.Call) and getattr(el.func, "id", None) == "K":
                    items.append(parse_k(el))
            lists[name] = items
    # KEYCODES_BASIC.extend(KEYCODES_BASIC_NUMPAD) etc.
    if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call) and getattr(node.value.func, "attr", None) == "extend":
        target = node.value.func.value.id
        src = node.value.args[0].id
        lists[target] = lists[target] + lists[src]

wanted = ["KEYCODES_SPECIAL", "KEYCODES_BASIC", "KEYCODES_SHIFTED", "KEYCODES_ISO", "KEYCODES_BOOT",
          "KEYCODES_MODIFIERS", "KEYCODES_QUANTUM", "KEYCODES_BACKLIGHT", "KEYCODES_MEDIA",
          "KEYCODES_MACRO_BASE"]
out = {}
for name in wanted:
    entries = []
    for k in lists.get(name, []):
        code = v6.get(k["id"])
        if code is None:
            print(f"// skipped {k['id']}: no v6 code", file=sys.stderr)
            continue
        row = [k["id"], code, k["label"]]
        extra = {}
        if k["tooltip"]: extra["t"] = k["tooltip"]
        if k["alias"]: extra["a"] = k["alias"]
        if k["masked"]: extra["m"] = 1
        if k["feature"]: extra["f"] = k["feature"]
        if extra: row.append(extra)
        entries.append(row)
    out[name.replace("KEYCODES_", "").lower()] = entries

consts = {k: v for k, v in v6.items() if k.startswith(("QK_", "MOD_", "ON_PRESS", "QMK_LM"))}

print("// GENERATED by tools/gen_keycodes.py from Vial GUI (vial-kb/vial-gui, GPL-2.0-or-later).")
print("// Keycode names, labels and v6 numbering exactly as Vial uses them. Do not edit by hand.")
print("/* eslint-disable */")
print("export type KcRow = [id: string, code: number, label: string, extra?: { t?: string; a?: string[]; m?: 1; f?: string }];")
print(f"export const V6: Record<string, number> = {json.dumps(consts, indent=0)};")
print(f"export const GROUPS: Record<string, KcRow[]> = {json.dumps(out, ensure_ascii=False, separators=(',', ':'))};")
