#!/usr/bin/env python3
"""Generate web/qmk-settings.ts from Vial GUI's qmk_settings.json (pure data)."""
import json, sys
d = json.load(open(sys.argv[1]))
width = {}
for tab in d["tabs"]:
    for f in tab["fields"]:
        w = f.get("width", 1)
        width[f["qsid"]] = max(width.get(f["qsid"], 1), w)
print("// GENERATED by tools/gen_settings.py from Vial GUI's qmk_settings.json (GPL-2.0-or-later).")
print("export interface SettingField { type: \"boolean\" | \"integer\"; title: string; qsid: number; width?: number; bit?: number; min?: number; max?: number }")
print("export interface SettingTab { name: string; fields: SettingField[] }")
print("export const QMK_SETTINGS: SettingTab[] = " + json.dumps(d["tabs"], indent=1) + ";")
print("/** Byte width of each setting id. */")
print("export const QMK_SETTINGS_WIDTH: Record<number, number> = " + json.dumps({str(k): v for k, v in sorted(width.items())}) + ";")
