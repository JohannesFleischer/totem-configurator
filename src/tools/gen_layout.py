#!/usr/bin/env python3
"""Turn the TOTEM's Vial KLE layout into absolute key positions (web/totem-geometry.ts).

Input: firmware/QMK/VIAL_source/totem/keymaps/vial/vial.json from GEIGEIGEIST/TOTEM.
Implements the kle-serial placement rules (rotation origin resets the cursor).
"""
import json, math, sys

d = json.load(open(sys.argv[1]))
rows = d["layouts"]["keymap"]
cur = dict(x=0.0, y=0.0, r=0.0, rx=0.0, ry=0.0, w=1.0, h=1.0)
cluster = dict(x=0.0, y=0.0)
keys = []
for row in rows:
    for k, item in enumerate(row):
        if isinstance(item, str):
            rc = item.split("\n")[0]
            r, c = map(int, rc.split(","))
            keys.append(dict(row=r, col=c, x=cur["x"], y=cur["y"], w=cur["w"], h=cur["h"],
                             r=cur["r"], rx=cur["rx"], ry=cur["ry"]))
            cur["x"] += cur["w"]
            cur["w"] = cur["h"] = 1.0
        else:
            if "r" in item: cur["r"] = item["r"]
            if "rx" in item:
                cur["rx"] = cluster["x"] = item["rx"]; cur["x"], cur["y"] = cluster["x"], cluster["y"]
            if "ry" in item:
                cur["ry"] = cluster["y"] = item["ry"]; cur["x"], cur["y"] = cluster["x"], cluster["y"]
            if "x" in item: cur["x"] += item["x"]
            if "y" in item: cur["y"] += item["y"]
            if "w" in item: cur["w"] = item["w"]
            if "h" in item: cur["h"] = item["h"]
    cur["y"] += 1
    cur["x"] = cur["rx"]

def corners(k):
    a = math.radians(k["r"])
    pts = []
    for dx, dy in ((0, 0), (k["w"], 0), (0, k["h"]), (k["w"], k["h"])):
        px, py = k["x"] + dx - k["rx"], k["y"] + dy - k["ry"]
        pts.append((k["rx"] + px * math.cos(a) - py * math.sin(a), k["ry"] + px * math.sin(a) + py * math.cos(a)))
    return pts

allp = [p for k in keys for p in corners(k)]
minx = min(p[0] for p in allp); miny = min(p[1] for p in allp)
maxx = max(p[0] for p in allp); maxy = max(p[1] for p in allp)
for k in keys:
    k["x"] -= minx; k["rx"] -= minx; k["y"] -= miny; k["ry"] -= miny
keys.sort(key=lambda k: (k["row"], k["col"]))
rnd = lambda v: round(v, 4)
print("// GENERATED by tools/gen_layout.py from the official TOTEM Vial definition")
print("// (GEIGEIGEIST/TOTEM firmware/QMK/VIAL_source/totem/keymaps/vial/vial.json).")
print("// Positions are in key units; each key rotates by r degrees around (rx, ry).")
print("export interface KeyGeom { row: number; col: number; x: number; y: number; w: number; h: number; r: number; rx: number; ry: number; }")
print(f"export const TOTEM_WIDTH = {rnd(maxx - minx)};")
print(f"export const TOTEM_HEIGHT = {rnd(maxy - miny)};")
print("export const TOTEM_KEYS: KeyGeom[] = [")
for k in keys:
    print("    { " + ", ".join(f"{n}: {rnd(k[n])}" for n in ("row", "col", "x", "y", "w", "h", "r", "rx", "ry")) + " },")
print("];")
print(f"// {len(keys)} keys", file=sys.stderr)
